import { readFile, writeFile } from 'node:fs/promises';
import { transform } from 'esbuild';
import { createHash } from 'node:crypto';
const shared = ['seo.js','editorial-copy.js','data.jsx','i18n.jsx','website-content.js','horizontal-rail.jsx','chrome.jsx','brand-pages.jsx','pages.jsx','app.jsx'];
const source = (await Promise.all(shared.map(file => readFile(file,'utf8')))).join('\n;\n');
const server = await transform(source, {loader:'jsx',target:'node22',jsx:'transform'});
const client = await transform(source + '\n;' + await readFile('visual-text-runtime.js','utf8'), {loader:'jsx',target:'es2020',jsx:'transform',minify:true});
const hash = createHash('sha256').update(client.code).digest('hex').slice(0,12);
await writeFile('site.bundle.js',client.code);
await writeFile('react.runtime.js', (await readFile('node_modules/react/umd/react.production.min.js','utf8')) + '\n;' + (await readFile('node_modules/react-dom/umd/react-dom.production.min.js','utf8')));
let template = await readFile('index.html','utf8');
template = template.replace(/site\.bundle\.js(?:\?v=[^"]*)?/, 'site.bundle.js?v=' + hash);
await writeFile('api/_site-source.js', `// Generated by scripts/build-site.mjs.\nexport const source = ${JSON.stringify(server.code)};\nexport const template = ${JSON.stringify(template)};\n`);
console.log('Built browser bundle and server rendering source.');
