import {readFileSync} from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const listeners = {}, properties = {}, documentListeners = {}, messages = [];
const element = {dataset:{p58Text:'title'},textContent:'Original',getAttribute:()=>null,removeAttribute:()=>{for(const k in properties)delete properties[k]},setAttribute:()=>{},style:{setProperty:(k,v)=>properties[k]=v},classList:{toggle:()=>{}}};
const parent = {postMessage:message=>messages.push(message)};
const document = {documentElement:{lang:'en'},getElementById:()=>({}),querySelectorAll:()=>[element],createElement:()=>({}),head:{append:()=>{}},addEventListener:(key,fn)=>documentListeners[key]=fn};
let computedSize='42px', computedWeight='500';
const context={URLSearchParams,location:{search:'?visualTextEditor=1',origin:'https://example.test'},parent,document,getComputedStyle:()=>({fontSize:computedSize,fontWeight:computedWeight}),MutationObserver:class{observe(){}},requestAnimationFrame:fn=>fn(),window:{addEventListener:(k,fn)=>listeners[k]=fn,DICT_I18N:{en:{title:'Original'}}}};
vm.runInNewContext(readFileSync('visual-text-runtime.js','utf8'),context);
const send=(origin,source,typography,text)=>listeners.message({origin,source,data:{type:'p58:text-preview',websiteTexts:{en:{title:text}},websiteTypography:{en:{title:typography}}}});
send('https://evil.test',parent,{},'Wrong');assert.equal(element.textContent,'Original');
send('https://example.test',{}, {},'Wrong');assert.equal(element.textContent,'Original');
send('https://example.test',parent,{size:42,font:'serif',weight:500},'<b>Literal text</b>');
assert.equal(element.textContent,'<b>Literal text</b>');assert.equal(properties['font-size'],'42px');assert.equal(properties['font-family'],'Georgia, serif');
send('https://example.test',parent,{size:999,font:'url(evil)',weight:999,padding:'50px'},'Safe');assert.deepEqual(properties,{});
send('https://example.test',parent,{},'');assert.equal(element.textContent,'');
element.dataset.p58Text='projectsPage.heroTitle';
element.textContent='Έργα από το projectsPage';
listeners.message({origin:'https://example.test',source:parent,data:{type:'p58:text-preview',websiteTexts:{en:{'projectsPage.heroTitle':'Wrong source'}},websiteTypography:{en:{'projectsPage.heroTitle':{size:48,font:'serif'}}}}});
assert.equal(element.textContent,'Έργα από το projectsPage','the bridge must not overwrite React-owned project text');
assert.equal(properties['font-size'],'48px');
let prevented=false, stopped=false;
documentListeners.click({target:{closest:()=>element},preventDefault:()=>{prevented=true;},stopImmediatePropagation:()=>{stopped=true;}});
assert.equal(messages.at(-1).key,'projectsPage.heroTitle');
assert.equal(messages.findLast(message=>message.type==='p58:text-selected').key,'projectsPage.heroTitle');
assert.ok(prevented && stopped,'selecting the hero text must not open its project');
assert.equal(messages.at(-1).type,'p58:text-metrics');
assert.equal(messages.at(-1).size,42);
const count=messages.length;
listeners.resize();
assert.equal(messages.length,count,'unchanged metrics must not create a message loop');
computedSize='31.5px';computedWeight='700';
listeners.resize();
assert.equal(messages.at(-1).size,31.5);
assert.equal(messages.at(-1).weight,'700');
document.documentElement.lang='el';
listeners.resize();
assert.equal(messages.at(-1).lang,'gr','metrics must identify the current preview language');
console.log('Passed: origin/source checks, literal text, typography allowlist, reset, empty text.');
